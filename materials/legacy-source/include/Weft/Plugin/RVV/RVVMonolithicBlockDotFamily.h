// The op-identity lookup (plugin side: from the recognized body op).
inline const MonolithicBlockDotOpEntry *
findMonolithicBlockDotOpEntry(mlir::Operation *op) {
  if (!op)
    return nullptr;
  llvm::StringRef name = op->getName().getStringRef();
  for (const MonolithicBlockDotOpEntry &entry : monolithicBlockDotOpTable())
    if (entry.opName == name)
      return &entry;
  return nullptr;
}

// The kind lookup (target side: from the candidate's op-derived kind metadata,
// where the op itself is no longer in hand).
inline const MonolithicBlockDotOpEntry *
findMonolithicBlockDotOpEntryByKind(llvm::StringRef kind) {
  if (kind.empty())
    return nullptr;
  for (const MonolithicBlockDotOpEntry &entry : monolithicBlockDotOpTable())
    if (entry.kind == kind)
      return &entry;
  // The repacked-GEVM / repacked-GEMM entries live outside the construction table
  // (see repackGemvMonolithicEntry / repackGemmMonolithicEntry); resolve their export
  // kind here so the target-side ABI/route lookup round-trips.
  if (kind == repackGemvMonolithicEntry().kind)
    return &repackGemvMonolithicEntry();
  if (kind == repackGemmMonolithicEntry().kind)
    return &repackGemmMonolithicEntry();
  return nullptr;
}

// Resolve the shared monolithic block-dot table entry for a SELECTED with_vl body
// op. Handles both body shapes the front door constructs: the compound single
// block-dot op (matched by op name), and the generic region-carrying typed flat
// block-dot LOOP body op (weft_rvv.typed_flat_block_dot_loop_body) the q8_0 front
// door substitutes for the compound q8_0 op. The loop body still exports through
// the SAME shared q8_0 Flat monolithic plan (same route id / kind / 8-role ABI),
// so it resolves to the existing q8_0 Flat table entry -- no new registry kind.
//
// EXCEPTION (q4_1 Family-B, q5_0/q5_1 five-bit): these typed loops carry the
// 4-role n/s/vx/vy ggml vec_dot ABI (NOT q8_0/q4_0's 8-role strided ABI), so each
// exports through its OWN Flat entry (the export ABI-arity gate rejects the 8-role
// q8_0 entry against the 4-role parameter list). They are distinguished from the
// q8_0/q4_0 default by their fold_model (q4_1/q5_1 scale_plus_min, q5_0
// scales_times_sumi); the q8_0/q4_0 default path is byte-unchanged. The
// scale_plus_min fold_model is a COLLISION -- q4_1 AND q5_1 both stamp it -- so it
// is no longer a unique key: a five-bit qh-source brick in the loop body breaks
// the tie to q5_1 (its OWN Flat entry / facts / route id), else q4_1.
inline const MonolithicBlockDotOpEntry *
resolveSelectedMonolithicBlockDotBodyEntry(mlir::Operation *op) {
  if (!op)
    return nullptr;
  if (const MonolithicBlockDotOpEntry *entry = findMonolithicBlockDotOpEntry(op))
    return entry;
  // The option-2 quant_contraction BRIDGE repacked-GEVM body: a single typed
  // weft_rvv.typed_repack_gemv_loop_body region that lowers directly through the
  // RVV->EmitC DialectConversion, so it shares the monolithic emission-plan +
  // object-export mechanism through its own RepackGemv route family. There is one
  // repacked GEVM (q4_0), so the op name alone resolves it -- no selector needed.
  if (op->getName().getStringRef() ==
      weft::rvv::TypedRepackGemvLoopBodyOp::getOperationName())
    return &repackGemvMonolithicEntry();
  // The option-2 quant_contraction BRIDGE repacked-GEMM (prefill) body: a single
  // typed weft_rvv.typed_repack_gemm_loop_body region that lowers directly through
  // the RVV->EmitC DialectConversion, so it shares the monolithic emission-plan +
  // object-export mechanism through its own RepackGemm route family. There is one
  // repacked GEMM (q4_0), so the op name alone resolves it -- no selector needed.
  if (op->getName().getStringRef() ==
      weft::rvv::TypedRepackGemmLoopBodyOp::getOperationName())
    return &repackGemmMonolithicEntry();
  if (op->getName().getStringRef() ==
      weft::rvv::TypedSuperBlockBlockDotLoopBodyOp::getOperationName()) {
    // The typed SUPER-BLOCK loop body carries the generic loop kind + a
    // fold_model that KEYS the accumulator arity: "super_block_two_level_scale_min"
    // (q4_K/q5_K DUAL -- positive fold PLUS the MIN term) resolves to a
    // SuperBlockTwoLevelScaleMin export entry; "scales_times_sumi" (q6_K SINGLE --
    // the no-min positive fold ONLY) resolves to a SuperBlockScalesTimesSumi entry;
    // "scalar_scale_min" (q2_K SCALAR -- the scalar `sumf += dall*isum - dmin*summs`
    // fold) resolves to a SuperBlockScalarScaleMin entry; "scalar_delta_grid" (iq1_s
    // SCALAR-grid -- the ternary-grid `sumf += d*((float)sumi + IQ1S_DELTA*
    // (float)sumi1)` fold) resolves to a SuperBlockScalarDeltaGrid entry. Within each
    // family the
    // selector alone is still ambiguous (q4_K and q5_K both dual), so DISAMBIGUATE
    // by the loop op's OWN weight_block_stride (block_q4_K 144 / block_q5_K 176 /
    // block_q6_K 210 / block_q2_K 84 / block_iq1_s 50) so each resolves to its OWN
    // export entry
    // (kind / ABI roles / facts). The typed super-block path depends on NO
    // GgmlBlockDotQ*KQ8KOp existing.
    auto foldModel = op->getAttrOfType<mlir::StringAttr>("fold_model");
    TypedFlatBlockDotLoopSelector wantSelector =
        TypedFlatBlockDotLoopSelector::SuperBlockTwoLevelScaleMin;
    if (foldModel && foldModel.getValue() == "scales_times_sumi")
      wantSelector = TypedFlatBlockDotLoopSelector::SuperBlockScalesTimesSumi;
    else if (foldModel && foldModel.getValue() == "scalar_scale_min")
      wantSelector = TypedFlatBlockDotLoopSelector::SuperBlockScalarScaleMin;
    else if (foldModel && foldModel.getValue() == "scalar_delta_grid")
      wantSelector = TypedFlatBlockDotLoopSelector::SuperBlockScalarDeltaGrid;
    std::int64_t stride = 0;
    if (auto strideAttr =
            op->getAttrOfType<mlir::IntegerAttr>("weight_block_stride"))
      stride = strideAttr.getInt();
    // STRIDE-66 COLLISION tie-breaker: block_tq2_0 and block_iq2_xxs BOTH have
    // weight_block_stride 66, and both export through fold_model "scalar_delta_grid"
    // (SuperBlockScalarDeltaGrid), so the (selector, stride) key alone is ambiguous.
    // They carry DISTINCT integer-core bricks -- tq2_0 the ARITHMETIC fused 2-bit
    // ternary core, iq2_xxs the GRID-of-8 vluxei16 gather core -- so disambiguate by
    // the region brick op type: a tq2_0 ternary-core body binds ONLY the tq2_0 entry,
    // and every other scalar_delta_grid body (iq2_xxs included) SKIPS the tq2_0 entry
    // and resolves by stride as before.
    bool hasTq20Core = false;
    op->walk([&](weft::rvv::GgmlBlockDotTQ20Q8KTernaryCoreOp) {
      hasTq20Core = true;
    });
    for (const MonolithicBlockDotOpEntry &entry : monolithicBlockDotOpTable()) {
      if (entry.typedFlatLoopSelector != wantSelector)
        continue;
      bool isTq20Entry = entry.opName == "weft_rvv.tq2_0_q8_k_block_dot";
      if (hasTq20Core != isTq20Entry)
        continue;
      for (const MonolithicBlockDotI64Attr &fact : entry.facts)
        if (fact.name == "weight_block_stride" && fact.value == stride)
          return &entry;
    }
    return nullptr;
  }
  if (op->getName().getStringRef() ==
      weft::rvv::TypedFlatBlockDotLoopBodyOp::getOperationName()) {
    // Route identity consumes the same final formula plan as emission.  The
    // older fold_model/qh/codebook reclassification duplicated compute
    // knowledge in the route layer and could disagree with the constructed
    // body.  Missing or unknown flat_* fields therefore fail closed here.
    auto bodyFamily =
        op->getAttrOfType<mlir::StringAttr>(kRVVFlatBodyFamilyAttr);
    auto decode =
        op->getAttrOfType<mlir::StringAttr>(kRVVFlatDecodePrimitiveAttr);
    auto fold =
        op->getAttrOfType<mlir::StringAttr>(kRVVFlatFoldModelAttr);
    auto bias =
        op->getAttrOfType<mlir::StringAttr>(kRVVFlatOffsetBiasAttr);
    auto weightScale = op->getAttrOfType<mlir::StringAttr>(
        kRVVFlatWeightScaleSourceAttr);
    if (!bodyFamily || !decode || !fold || !bias || !weightScale)
      return nullptr;

    std::optional<TypedFlatBlockDotLoopSelector> selector;
    if (bodyFamily.getValue() == "binary-two-level" &&
        decode.getValue() == "binary-sign" &&
        fold.getValue() == "binary-two-level")
      selector = TypedFlatBlockDotLoopSelector::Q10BinarySign;
    else if (bodyFamily.getValue() == "nvfp4-codebook" &&
             decode.getValue() == "nvfp4-codebook" &&
             fold.getValue() == "nvfp4-codebook")
      selector = TypedFlatBlockDotLoopSelector::NVFP4Codebook;
    else if (bodyFamily.getValue() == "shared" &&
             decode.getValue() == "unsigned-nibble" &&
             fold.getValue() == "scale-plus-min")
      selector = TypedFlatBlockDotLoopSelector::ScalePlusMin;
    else if (bodyFamily.getValue() == "shared" &&
             decode.getValue() == "five-bit-offset-binary" &&
             fold.getValue() == "scale-plus-min" &&
             bias.getValue() == "none")
      selector = TypedFlatBlockDotLoopSelector::ScalePlusMinFiveBitQh;
    else if (bodyFamily.getValue() == "shared" &&
             decode.getValue() == "five-bit-offset-binary" &&
             fold.getValue() == "scales-times-sumi" &&
             bias.getValue() == "required")
      selector = TypedFlatBlockDotLoopSelector::ScalesTimesSumi;
    else if (bodyFamily.getValue() == "shared" &&
             decode.getValue() == "codebook-gather-nibble" &&
             weightScale.getValue() == "fp16")
      selector = TypedFlatBlockDotLoopSelector::Iq4NlCodebook;
    else if (bodyFamily.getValue() == "shared" &&
             (decode.getValue() == "plain-i8" ||
              decode.getValue() == "offset-binary-nibble"))
      selector = TypedFlatBlockDotLoopSelector::Q8Default;
    if (!selector)
      return nullptr;
    for (const MonolithicBlockDotOpEntry &entry : monolithicBlockDotOpTable())
      if (entry.typedFlatLoopSelector == *selector)
        return &entry;
  }
  return nullptr;
}

// Recognize a selected with_vl scope whose ENTIRE compute body is exactly one
// supported monolithic ggml block-dot op (any family) OR the generic typed flat
// block-dot loop body op. Returns the op for that single-op body; nullptr
// otherwise -- so decomposed route bodies (and unwired block-dot ops) fall
// through to the slice-based route path unchanged.
inline mlir::Operation *
findSelectedMonolithicBlockDotBody(weft::rvv::WithVLOp withVL) {
  if (withVL.getBody().empty())
    return nullptr;
  mlir::Block &block = withVL.getBody().front();
  mlir::Operation *found = nullptr;
  for (mlir::Operation &op : block) {
    if (!resolveSelectedMonolithicBlockDotBodyEntry(&op))
      return nullptr; // any non-family op => not the monolithic single-op shape
    if (found)
      return nullptr; // more than one op => not the monolithic single-op shape
    found = &op;
  }
  return found;
}

